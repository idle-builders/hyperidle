#!/usr/bin/env npx tsx
/**
 * AU28 — regenerate `governance/baseline.json` from the violations that actually exist.
 *
 * Run by a person, never by `npm run lint` and never in CI. Committing the result is the act that
 * makes the debt visible in the diff — which is the property convention alone failed to provide.
 *
 * Usage:
 *   npx tsx scripts/governance-baseline.ts            # print what would change
 *   npx tsx scripts/governance-baseline.ts --write    # rewrite the file
 */

import { writeFileSync } from "node:fs";
import path from "node:path";

import {
	buildCrossings,
	buildLiveCensus,
	loadArchitecture,
	loadBaseline,
	REPO_ROOT,
	trackedFiles,
} from "./governance-context.js";
import type { Baseline, BaselineGroup } from "./lib/crossing-report.js";
import { refuseGrowth } from "./lib/crossing-report.js";
import { liveGroups, violationsOf } from "./rules/crossings.js";

const adopted = process.argv.reduce<string[]>((acc, arg, i) => (arg === "--adopt" ? [...acc, process.argv[i + 1] ?? ""] : acc), []);

const architecture = loadArchitecture();
const census = buildLiveCensus(architecture, trackedFiles());

const detected = buildCrossings(census, architecture);
const groups = liveGroups(violationsOf(architecture, detected.crossings));

// Sorted throughout — a baseline whose diff reorders on every run is unreadable.
const out: Record<string, BaselineGroup> = {};
for (const group of [...groups].sort((a, b) => a.key.localeCompare(b.key))) {
	const sites: Record<string, number> = {};
	for (const [file, count] of [...group.sites].sort((a, b) => a[0].localeCompare(b[0]))) sites[file] = count;
	out[group.key] = { sites };
}

const baseline: Baseline = {
	governanceBaseline: true,
	note:
		"Known architecture violations, and the ONLY things that warn instead of erroring. This file " +
		"may only ever shrink. Generated by `npm run governance:baseline` — never edited by hand, never " +
		"regenerated by CI — and the generator REFUSES to add a group or raise a count, so a new " +
		"violation cannot be parked here. Clearing a group's last site deletes the entry, and from that " +
		"commit the rule is at error: promotion is what fixing the violation does, not a later step. " +
		"The check fails in both directions — growth is new debt, and a shrink that is not committed is " +
		"how a ratchet becomes a rubber stamp.",
	groups: out,
};

const violationsIn = (groups: Record<string, BaselineGroup>, world: string): number =>
	Object.entries(groups)
		.filter(([key]) => key.endsWith(` ${world}`))
		.reduce((n, [, g]) => n + Object.values(g.sites).reduce((m, c) => m + c, 0), 0);

const previous = loadBaseline();

const refusals = refuseGrowth(groups, previous, adopted);
if (refusals.length > 0) {
	console.error(`governance baseline: REFUSED — ${refusals.length} group(s)/site(s) would grow the baseline.\n`);
	for (const refusal of refusals) console.error(`  ${refusal}`);
	console.error("\n  The baseline is a shrinking record of known debt, not a place to put new debt.");
	process.exit(1);
}

// Production and development are totalled separately — they are different kinds of debt, and one
// number lets the smaller, more serious half move unnoticed behind the larger one.
console.log(`governance baseline: ${Object.keys(out).length} group(s)`);
for (const world of ["production", "development"]) {
	const now = violationsIn(out, world);
	const before = violationsIn(previous.groups as Record<string, BaselineGroup>, world);
	const delta = now - before;
	console.log(`  ${world.padEnd(12)} ${String(now).padStart(5)} violation(s)   was ${before}   delta ${delta >= 0 ? "+" : ""}${delta}`);
}
if (process.argv.includes("--write")) {
	writeFileSync(path.join(REPO_ROOT, "governance/baseline.json"), `${JSON.stringify(baseline, null, "\t")}\n`);
	console.log("  written to governance/baseline.json");
} else {
	console.log("  (dry run — pass --write to rewrite the file)");
}

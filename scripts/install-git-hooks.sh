#!/bin/sh
# Wire this clone's git hooks to the tracked scripts in .githooks/.
# Run from `npm install` (package.json `prepare`), so a clone that installs
# dependencies once has its hooks in place from then on.
#
# @lore: a relative `core.hooksPath` (e.g. ".githooks") does NOT work for
# worktrees — git resolves it against the tree you INVOKE from, so
# `git worktree add` looks for the hook in the *old* worktree, not the new one.
# Verified empirically: a branch carrying .githooks gets no hook run when the
# invoking tree lacks it. So we point core.hooksPath at the absolute, shared
# .git/hooks and install a shim there that forwards to the tracked script.
# That is also the path Claude Code pins in each worktree's `config.worktree`
# (it sets extensions.worktreeConfig=true and overrides core.hooksPath), so
# both agent-made and hand-made worktrees end up running the same hook.

set -e

git rev-parse --git-dir >/dev/null 2>&1 || exit 0

common=$(git rev-parse --git-common-dir)
case "$common" in
/*) ;;
*) common="$(pwd)/$common" ;;
esac
mkdir -p "$common/hooks"

# Absolute, and shared by every worktree of this clone.
git config core.hooksPath "$common/hooks"

for hook in post-checkout; do
	shim="$common/hooks/$hook"
	cat >"$shim" <<SHIM
#!/bin/sh
# Generated by scripts/install-git-hooks.sh — forwards to the tracked hook.
# Prefer the copy in the tree being checked out; fall back to the main checkout
# so worktrees cut from a commit that predates .githooks still bootstrap.
for candidate in \\
	"\$(git rev-parse --show-toplevel 2>/dev/null)/.githooks/$hook" \\
	"$common/../.githooks/$hook"; do
	if [ -x "\$candidate" ]; then
		exec "\$candidate" "\$@"
	fi
done
exit 0
SHIM
	chmod +x "$shim"
done
